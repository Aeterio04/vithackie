from kawach.storage import artifacts as storage
from kawach.storage.secrets import read_secret_password


def _extract_journeys_from_edges(edges: List[ActionEdge], states: List[StateNode]) -> List[Journey]:
    """Helper to extract simple paths with depth >= 3 if not already generated by crawler."""
    adj: Dict[str, List[ActionEdge]] = {}
    for e in edges:
        adj.setdefault(e.fromState, []).append(e)

    root_state_ids = [s.stateId for s in states if s.depth == 0]
    journeys: List[Journey] = []
    max_journeys = 10

    def dfs(current_path: List[ActionEdge], visited_states: Set[str]):
        if len(journeys) >= max_journeys:
            return
        if len(current_path) >= 3:
            j_id = f"journey_{len(journeys) + 1}"
            first_from = states_by_id.get(current_path[0].fromState)
            start_url = first_from.url if first_from else "Root"
            title = f"{start_url} -> {' -> '.join(e.action for e in current_path[:4])}"
            steps = [f"{e.action} [{e.locator}]" + (f" ({e.value})" if e.value else "") for e in current_path]
            journeys.append(Journey(journeyId=j_id, title=title, depth=len(current_path), steps=steps))
            if len(current_path) >= 6:
                return

        last_edge = current_path[-1]
        for next_edge in adj.get(last_edge.toState, []):
            if next_edge.toState not in visited_states:
                visited_states.add(next_edge.toState)
                dfs(current_path + [next_edge], visited_states)
                visited_states.remove(next_edge.toState)

    states_by_id = {s.stateId: s for s in states}
    for root_id in root_state_ids:
        for edge in adj.get(root_id, []):
            dfs([edge], {root_id, edge.toState})

    return journeys


def run_explorer(run_id: str) -> AppMap:
    """Crawl the target web application with deep state-graph exploration and generate an AppMap."""
    run_input = storage.load_model(run_id, "input.json", RunInput)
    base_url = run_input.targetUrl if run_input else "http://localhost:4000"
    username = run_input.username if run_input else ""
    password = read_secret_password(run_id)
    background_prompt = run_input.prompt if run_input and run_input.prompt else "Web application under test."

    max_pages = run_input.budgets.maxPages if (run_input and run_input.budgets) else settings.MAX_PAGES
    explore_seconds = run_input.budgets.exploreSeconds if (run_input and run_input.budgets) else settings.EXPLORE_SECONDS

    storage.set_stage(run_id, "exploring", step="Starting browser", done=0, total=max_pages)

    out_file = (storage.run_dir(run_id) / "explore_raw.json").resolve()

    runner_dir = (settings.repo_root / "apps" / "runner").resolve()
    env = os.environ.copy()
    env["BASE_URL"] = base_url
    env["TEST_USERNAME"] = username
    env["TEST_PASSWORD"] = password
    env["MAX_PAGES"] = str(max_pages)
    env["EXPLORE_SECONDS"] = str(explore_seconds)
    env["MAX_DEPTH"] = "4"
    env["MAX_TRANSITIONS"] = "60"
    env["MAX_PER_DEPTH"] = "20"
    env["ALLOWED_HOSTS"] = ",".join(settings.ALLOWED_HOSTS)
    env["OUT_FILE"] = str(out_file)

    cmd = ["npx", "tsx", "explore.ts"]
    if os.name == "nt":
        cmd = ["cmd", "/c", "npx", "tsx", "explore.ts"]

    def _log(msg: str, **kwargs):
        try:
            from kawach.storage.artifacts import log_pipeline
            log_pipeline(run_id, msg, **kwargs)
        except Exception:
            pass

    _log(
        f"Exploratory Worker: Launching Chromium crawler against {base_url} (budget: {max_pages} pages, {explore_seconds}s, depth: L0–L3+)...",
        source="explorer",
    )

    stderr_chunks: List[str] = []
    try:
        proc = subprocess.Popen(
            cmd,
            cwd=str(runner_dir),
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            bufsize=1,
        )

        timeout_seconds = explore_seconds + 60
        start_wait = time.time()

        page_pattern = re.compile(r"^PAGE\s+(\d+)/(\d+)\s+(.*)$")
        state_pattern = re.compile(r"^STATE\s+(\S+)\s+depth=(\d+)\s+(.*)$")
        action_pattern = re.compile(r"^ACTION\s+\[L(\d+)\]\s+(\S+)\s+on\s+(.*)$")

        if proc.stdout:
            for line in iter(proc.stdout.readline, ""):
                line_str = line.strip()
                if not line_str:
                    continue

                page_match = page_pattern.match(line_str)
                if page_match:
                    done_n = int(page_match.group(1))
                    total_n = int(page_match.group(2))
                    page_path = page_match.group(3)
                    storage.set_stage(
                        run_id,
                        "exploring",
                        step=f"Crawling {page_path}",
                        done=done_n,
                        total=total_n,
                    )
                    _log(
                        f"Exploratory Worker: Scraped page {page_path} ({done_n}/{total_n})",
                        source="explorer",
                    )
                    continue

                state_match = state_pattern.match(line_str)
                if state_match:
                    s_id = state_match.group(1)
                    s_depth = state_match.group(2)
                    s_url = state_match.group(3)
                    _log(
                        f"Exploratory Worker: Discovered state {s_id} (L{s_depth}) at {s_url}",
                        source="explorer",
                    )
                    continue

                act_match = action_pattern.match(line_str)
                if act_match:
                    act_depth = act_match.group(1)
                    act_type = act_match.group(2)
                    act_loc = act_match.group(3)
                    _log(
                        f"Exploratory Worker: Executed [L{act_depth}] {act_type} on {act_loc}",
                        source="explorer",
                    )
                    continue

                if time.time() - start_wait > timeout_seconds:
                    proc.kill()
                    break

        _, stderr_text = proc.communicate(timeout=10)
        if stderr_text:
            stderr_chunks.append(stderr_text)

    except Exception as crawl_err:
        stderr_chunks.append(f"Subprocess execution error: {crawl_err}")

    raw_data = storage.read_json(run_id, "explore_raw.json")
    if not raw_data or not isinstance(raw_data, dict):
        err_tail = "".join(stderr_chunks)[-500:] if stderr_chunks else "No output file produced."
        raw_data = {
            "baseUrl": base_url,
            "generatedAt": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "login": {"attempted": False, "success": False, "url": None, "note": None},
            "pages": [],
            "summary": "(summary unavailable)",
            "features": [],
            "stats": {"pagesVisited": 0, "durationSeconds": 0.0, "budgetHit": None, "statesDiscovered": 0, "transitionsExecuted": 0},
            "states": [],
            "edges": [],
            "journeys": [],
            "unexploredFrontier": [],
            "error": f"Explorer produced no output: {err_tail}",
        }

    # Ensure graph lists exist in raw_data
    raw_data.setdefault("states", [])
    raw_data.setdefault("edges", [])
    raw_data.setdefault("journeys", [])
    raw_data.setdefault("unexploredFrontier", [])
    raw_data.setdefault("stats", {"pagesVisited": len(raw_data.get("pages", [])), "durationSeconds": 0.0, "budgetHit": None, "statesDiscovered": len(raw_data.get("states", [])), "transitionsExecuted": len(raw_data.get("edges", []))})

    # Validate or enrich journeys (paths depth >= 3)
    if not raw_data.get("journeys") and raw_data.get("edges") and raw_data.get("states"):
        parsed_edges = [ActionEdge.model_validate(e) for e in raw_data["edges"]]
        parsed_states = [StateNode.model_validate(s) for s in raw_data["states"]]
        extracted = _extract_journeys_from_edges(parsed_edges, parsed_states)
        raw_data["journeys"] = [j.model_dump() for j in extracted]

    storage.set_stage(run_id, "exploring", step="Synthesizing app map summary", done=max_pages, total=max_pages)

    compact_pages = []
    for p in raw_data.get("pages", []):
        compact_pages.append({
            "path": p.get("path"),
            "title": p.get("title"),
            "requiresAuth": p.get("requiresAuth", False),
            "headings": [h.get("text") for h in p.get("headings", [])[:5]],
            "forms": [
                {
                    "id": f.get("id"),
                    "method": f.get("method"),
                    "fields": [
                        {
                            "label": fld.get("label"),
                            "type": fld.get("type"),
                            "role": fld.get("role"),
                        }
                        for fld in f.get("fields", [])
                    ],
                }
                for f in p.get("forms", [])
            ],
            "buttons": [b.get("text") for b in p.get("buttons", [])[:8]],
            "consoleErrorCount": len(p.get("consoleErrors", [])),
        })

    # Include deep journeys in synthesis context if present
    journeys_summary = []
    for j in raw_data.get("journeys", [])[:6]:
        journeys_summary.append({
            "title": j.get("title"),
            "depth": j.get("depth"),
            "steps": j.get("steps", [])[:5],
        })

    synthesis_payload = {
        "pages": compact_pages,
        "deepJourneys": journeys_summary,
        "statesDiscovered": len(raw_data.get("states", [])),
    }

    compact_str = json.dumps(synthesis_payload, ensure_ascii=False)[:12000]

    try:
        prompt_text = load_prompt(
            "explore_summary",
            guard=guard(),
            prompt=background_prompt,
            app_map=untrusted(compact_str, "app_map"),
        )
        llm = get_llm()
        summary_resp = llm.complete_json(
            system="You are an expert QA and software architect analysing web application crawler results.",
            prompt=prompt_text,
            schema_name="explore_summary",
            run_id=run_id,
        )
        if isinstance(summary_resp, dict):
            summary = summary_resp.get("summary", "")
            features_raw = summary_resp.get("features", [])
        else:
            summary = "(summary unavailable)"
            features_raw = []
    except Exception:
        summary = "(summary unavailable)"
        features_raw = []

    raw_data["summary"] = summary
    raw_data["features"] = features_raw
    raw_data["generatedAt"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    app_map = AppMap.model_validate(raw_data)
    storage.save_model(run_id, "app_map.json", app_map)

    return app_map
